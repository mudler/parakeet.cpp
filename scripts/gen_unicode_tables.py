#!/usr/bin/env python3
"""Generate src/unicode_props_data.hpp: compact Unicode property tables.

The byte-level BPE pre-tokenizer (src/bpe_tokenizer.cpp) needs the classes
\\p{Lu} \\p{Ll} \\p{Lt} \\p{Lm} \\p{Lo} \\p{M} \\p{N} and White_Space. Each code
point gets a small bit mask; consecutive code points with the same mask are
merged into one range. The table stores only the first code point of each
range (the range ends where the next one starts; mask 0 means none of the
classes).

The data comes from the Unicode Character Database files
extracted/DerivedGeneralCategory.txt and PropList.txt. The version is pinned
to 16.0.0: this is the version the HF `tokenizers` regex engine (Oniguruma)
uses, which was measured by comparing every code point (see docs/bpe-tokenizer.md).
Python's `unicodedata` is not used because its version depends on the
interpreter.

Regenerate with:
    python3 scripts/gen_unicode_tables.py --ucd-dir DIR --fetch > src/unicode_props_data.hpp
    (--fetch downloads the two files from unicode.org into DIR when missing)
"""
import argparse
import os
import re
import sys
import urllib.request

VERSION = "16.0.0"
BASE = "https://www.unicode.org/Public/%s/ucd/" % VERSION
FILES = {"DerivedGeneralCategory.txt": "extracted/DerivedGeneralCategory.txt", "PropList.txt": "PropList.txt"}

# Bit order must match enum in src/unicode_props.hpp.
BITS = {"Lu": 1, "Ll": 2, "Lt": 4, "Lm": 8, "Lo": 16, "M": 32, "N": 64, "WS": 128}


def read_ranges(path):
    """Yield (lo, hi, value) from a UCD file of `XXXX..YYYY ; value # comment` lines."""
    pat = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z_]+)")
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = pat.match(line)
            if m:
                lo = int(m.group(1), 16)
                yield lo, int(m.group(2) or m.group(1), 16), m.group(3)


def check_version(path):
    with open(path, encoding="utf-8") as f:
        head = f.readline()
    if VERSION not in head:
        sys.exit("%s is not Unicode %s: %s" % (path, VERSION, head.strip()))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ucd-dir", required=True)
    ap.add_argument("--fetch", action="store_true", help="download missing files")
    args = ap.parse_args()
    for name, rel in FILES.items():
        p = os.path.join(args.ucd_dir, name)
        if not os.path.exists(p):
            if not args.fetch:
                sys.exit("missing %s (use --fetch)" % p)
            os.makedirs(args.ucd_dir, exist_ok=True)
            urllib.request.urlretrieve(BASE + rel, p)
    gc_path = os.path.join(args.ucd_dir, "DerivedGeneralCategory.txt")
    pl_path = os.path.join(args.ucd_dir, "PropList.txt")
    check_version(gc_path)
    check_version(pl_path)

    mask = [0] * 0x110000
    for lo, hi, cat in read_ranges(gc_path):
        if cat in ("Lu", "Ll", "Lt", "Lm", "Lo"):
            b = BITS[cat]
        elif cat[0] == "M":
            b = BITS["M"]
        elif cat[0] == "N":
            b = BITS["N"]
        else:
            continue
        for cp in range(lo, hi + 1):
            mask[cp] |= b
    for lo, hi, prop in read_ranges(pl_path):
        if prop == "White_Space":
            for cp in range(lo, hi + 1):
                mask[cp] |= BITS["WS"]

    starts = []
    prev = 0
    for cp, m in enumerate(mask):
        if m != prev:
            starts.append((cp, m))
            prev = m
    out = []
    out.append("// Generated by scripts/gen_unicode_tables.py. Do not edit.")
    out.append("// Unicode version: %s" % VERSION)
    out.append("#pragma once")
    out.append("#include <cstdint>")
    out.append("namespace pk { namespace unicode_data {")
    out.append('static const char* const kUnicodeVersion = "%s";' % VERSION)
    out.append("struct Range { uint32_t start; uint32_t mask; };")
    out.append("// Sorted by start. A range ends where the next one starts.")
    out.append("static const Range kRanges[] = {")
    line = "   "
    for cp, m in starts:
        item = " {0x%X,%d}," % (cp, m)
        if len(line) + len(item) > 96:
            out.append(line)
            line = "   "
        line += item
    out.append(line)
    out.append("};")
    out.append("static const uint32_t kNumRanges = %d;" % len(starts))
    out.append("}} // namespace pk::unicode_data")
    print("\n".join(out))


if __name__ == "__main__":
    main()
